-- Set the S3 bucket and an existing Snowflake storage integration before running.
CREATE DATABASE IF NOT EXISTS MOBILITY;
CREATE SCHEMA IF NOT EXISTS MOBILITY.ANALYTICS;

CREATE OR REPLACE STAGE MOBILITY.ANALYTICS.TRIPS_STAGE
  URL = 's3://YOUR_BUCKET/mobility/nyc-taxi-2023/'
  STORAGE_INTEGRATION = YOUR_S3_INTEGRATION
  FILE_FORMAT = (TYPE = PARQUET);

CREATE TABLE IF NOT EXISTS MOBILITY.ANALYTICS.TRIPS (
  TRIP_ID VARCHAR,
  ROUTE_ID VARCHAR,
  ORIGIN_ZONE INTEGER,
  DESTINATION_ZONE INTEGER,
  EVENT_TIME TIMESTAMP_NTZ,
  DURATION_S INTEGER,
  DISTANCE_KM FLOAT,
  SPEED_KMH FLOAT
);

COPY INTO MOBILITY.ANALYTICS.TRIPS
  FROM (
    SELECT $1:trip_id::VARCHAR, $1:route_id::VARCHAR,
          $1:origin_zone::INTEGER, $1:destination_zone::INTEGER,
          $1:event_time::TIMESTAMP_NTZ, $1:duration_s::INTEGER,
          $1:distance_km::FLOAT, $1:speed_kmh::FLOAT
    FROM @MOBILITY.ANALYTICS.TRIPS_STAGE
  )
  FILE_FORMAT = (TYPE = PARQUET)
  ON_ERROR = ABORT_STATEMENT;

-- Peak hours by pickup time in New York local time.
SELECT DATE_TRUNC('hour', EVENT_TIME) AS HOUR_LOCAL,
        COUNT(*) AS TRIPS, AVG(SPEED_KMH) AS MEAN_SPEED_KMH
FROM MOBILITY.ANALYTICS.TRIPS
GROUP BY 1 ORDER BY TRIPS DESC LIMIT 24;

-- High-volume slow routes; slow share is a proxy, not measured road congestion.
SELECT ROUTE_ID, ORIGIN_ZONE, DESTINATION_ZONE,
        COUNT(*) AS TRIPS, AVG(DURATION_S) / 60 AS MEAN_MINUTES,
        AVG(IFF(SPEED_KMH < 15, 1, 0)) AS SLOW_SHARE
FROM MOBILITY.ANALYTICS.TRIPS
GROUP BY 1, 2, 3 HAVING COUNT(*) >= 30
ORDER BY SLOW_SHARE DESC, TRIPS DESC LIMIT 20;

-- Most active origin zones.
SELECT ORIGIN_ZONE, COUNT(*) AS DEPARTURES
FROM MOBILITY.ANALYTICS.TRIPS
GROUP BY 1 ORDER BY DEPARTURES DESC LIMIT 20;
